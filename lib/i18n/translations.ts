export type TranslationKey = keyof typeof translations.en;

export function getCategoryTranslation(slugOrName: string, lang: Language): string {
  const s = (slugOrName || "").toLowerCase();
  if (s.includes("women") || s.includes("dress")) return translations[lang].cat_womens_fashion;
  if (s.includes("men") && !s.includes("women")) return translations[lang].cat_mens_fashion;
  if (s.includes("electro") || s.includes("phone") || s.includes("computer")) return translations[lang].cat_electronics;
  if (s.includes("health") || s.includes("beauty")) return translations[lang].cat_health_beauty;
  if (s.includes("home") || s.includes("living")) return translations[lang].cat_home_living;
  if (s.includes("book") || s.includes("stationery")) return translations[lang].cat_books_stationery;
  if (s.includes("grocer") || s.includes("food") || s.includes("coffee")) return translations[lang].cat_groceries;
  if (s.includes("toy") || s.includes("baby")) return translations[lang].cat_toys_baby;
  if (s.includes("sport") || s.includes("outdoor")) return translations[lang].cat_sports;
  if (s.includes("vehicle") || s.includes("car") || s.includes("auto")) return translations[lang].cat_vehicles;
  return slugOrName;
}
